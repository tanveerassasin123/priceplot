import type { ProductOffer } from "@/lib/offers/types";
import { applyPriceToOffer } from "@/lib/pricing/calculator";

function offer(
  partial: Omit<ProductOffer, "finalPrice" | "isDemo" | "lastChecked" | "verificationStatus"> &
    Partial<Pick<ProductOffer, "finalPrice" | "isDemo" | "lastChecked" | "verificationStatus">>,
): ProductOffer {
  return applyPriceToOffer({
    isDemo: true,
    lastChecked: new Date().toISOString(),
    verificationStatus: partial.verificationStatus ?? "verified",
    ...partial,
  });
}

